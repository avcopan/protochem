"""Generate the element table, `src/element/data.rs`, from the mendeleev database.

Run with `pixi run elements-data`.

The generated file holds a single `static ELEMENTS: [Element; 118]`, ordered by
atomic number, and expects the parent module (`src/element.rs`) to define:

    pub struct Element {
        atomic_number: u8,
        symbol: &'static str,
        mass_number: u16,
        mass: f64,
        group: Option<u8>,
        period: u8,
        covalent_radius: f64,
        valence_electrons: u8,
        electronegativity: Option<f64>,
    }

A child module can see its parent's private fields, so the fields can stay private.
"""

from collections.abc import Callable
from pathlib import Path

from mendeleev import get_all_elements
from mendeleev.models import Element, Isotope

OUTPUT_PATH = Path(__file__).parent.parent / "src" / "element" / "data.rs"

HEADER = """\
//! The element table. Generated by `scripts/elements_data.py`: do not edit by hand.
//!
//! Source: the mendeleev database. Each element's mass and mass number are those of
//! its most abundant isotope or, for elements without a stable isotope, of the
//! isotope that sets its conventional atomic weight (e.g. technetium-98).
//! Covalent radii are the Pyykkö single-bond radii, in angstroms. Electronegativities
//! are Pauling values.

use super::Element;

/// All known elements, ordered by atomic number, so `ELEMENTS[z - 1]` has atomic
/// number `z`.
#[allow(clippy::unreadable_literal)] // full-precision masses, from Python's `repr`
#[rustfmt::skip]
pub(super) static ELEMENTS: [Element; {count}] = [
"""

FOOTER = "];\n"


def representative_isotope(element: Element) -> Isotope:
    """Pick the isotope whose mass and mass number represent the element.

    Args:
        element: The element.

    Returns:
        The most abundant isotope, or for elements without natural abundance data,
        the isotope whose mass number matches the conventional atomic weight.

    Raises:
        ValueError: If no isotope matches.
    """
    natural = [i for i in element.isotopes if i.abundance]
    if natural:
        return max(natural, key=lambda i: i.abundance)

    mass_number = round(element.atomic_weight)
    for isotope in element.isotopes:
        if isotope.mass_number == mass_number:
            return isotope

    msg = f"No isotope of {element.symbol} with mass number {mass_number}"
    raise ValueError(msg)


def rust_float(value: float) -> str:
    """Format a float as a Rust literal.

    Python's `repr` gives the shortest string that round-trips, which Rust parses to
    the same `f64`.

    Args:
        value: The value.

    Returns:
        The Rust literal.
    """
    return repr(float(value))


def rust_option[T](value: T | None, fmt: Callable[[T], str]) -> str:
    """Format an optional value as a Rust `Option` literal.

    Args:
        value: The value, or `None`.
        fmt: Formatter for a present value.

    Returns:
        The Rust literal.
    """
    return "None" if value is None else f"Some({fmt(value)})"


def element_row(element: Element) -> str:
    """Format one element as a Rust struct literal.

    Args:
        element: The element.

    Returns:
        One line of the `ELEMENTS` array.
    """
    isotope = representative_isotope(element)
    fields = {
        "atomic_number": str(element.atomic_number),
        "symbol": f'"{element.symbol}"',
        "mass_number": str(isotope.mass_number),
        "mass": rust_float(isotope.mass),
        "group": rust_option(element.group_id, str),
        "period": str(element.period),
        "covalent_radius": rust_float(element.covalent_radius_pyykko / 100),
        "valence_electrons": str(element.nvalence()),
        "electronegativity": rust_option(element.en_pauling, rust_float),
    }
    body = ", ".join(f"{key}: {value}" for key, value in fields.items())
    return f"    Element {{ {body} }},\n"


def main() -> None:
    """Write the element table.

    Raises:
        ValueError: If the elements are not numbered 1, 2, ..., N.
    """
    elements = sorted(get_all_elements(), key=lambda e: e.atomic_number)
    numbers = [e.atomic_number for e in elements]
    if numbers != list(range(1, len(elements) + 1)):
        msg = f"Atomic numbers are not contiguous from 1: {numbers}"
        raise ValueError(msg)

    rows = "".join(element_row(e) for e in elements)
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(HEADER.format(count=len(elements)) + rows + FOOTER)


if __name__ == "__main__":
    main()
